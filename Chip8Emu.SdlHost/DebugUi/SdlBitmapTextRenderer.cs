using SDL3;

namespace Chip8Emu.SdlHost.Debug
{
    internal sealed class SdlBitmapTextRenderer
    {
        private readonly nint _renderer;
        private readonly Dictionary<char, string[]> _glyphs = BuildGlyphs();

        public SdlBitmapTextRenderer(nint renderer)
        {
            _renderer = renderer;
        }

        public void DrawText(string text, float x, float y, float scale, byte r, byte g, byte b, byte a = 255)
        {
            SDL.SetRenderDrawColor(_renderer, r, g, b, a);
            var cursorX = x;
            foreach (var ch in text.ToUpperInvariant())
            {
                DrawGlyph(ch, cursorX, y, scale);
                cursorX += 4f * scale;
            }
        }

        private void DrawGlyph(char ch, float x, float y, float scale)
        {
            if (!_glyphs.TryGetValue(ch, out var rows))
            {
                rows = _glyphs['?'];
            }

            for (var row = 0; row < rows.Length; row++)
            {
                var pattern = rows[row];
                for (var col = 0; col < pattern.Length; col++)
                {
                    if (pattern[col] != '1')
                    {
                        continue;
                    }

                    var rect = new SDL.FRect
                    {
                        X = x + (col * scale),
                        Y = y + (row * scale),
                        W = scale,
                        H = scale
                    };
                    SDL.RenderFillRect(_renderer, ref rect);
                }
            }
        }

